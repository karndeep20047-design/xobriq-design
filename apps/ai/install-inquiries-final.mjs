import { writeFileSync, mkdirSync, existsSync, statSync, rmSync } from "node:fs";
import { dirname } from "node:path";

// Angle brackets constructed at runtime — the LITERAL characters `<` and `>`
// never appear in JSX-looking positions in this file's source code.
// This immunizes the script against paste corruption.
const LT = String.fromCharCode(60);
const GT = String.fromCharCode(62);

